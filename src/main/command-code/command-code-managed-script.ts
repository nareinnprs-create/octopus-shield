import { posixCurlCommand } from '../agent-hooks/hook-post-command'
import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%OSHIELD_AGENT_HOOK_PORT%"=="" if defined OSHIELD_AGENT_HOOK_ENDPOINT if exist "%OSHIELD_AGENT_HOOK_ENDPOINT%" call "%OSHIELD_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%OSHIELD_AGENT_HOOK_TOKEN%"=="" if not "%OSHIELD_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\shield-dev\\agent-hooks" for /r "%APPDATA%\\shield-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      // Per-worktree `pnpm dev` profiles live one level down; FOR /R cannot take a FOR variable as its root.
      'if "%OSHIELD_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\shield-dev-wt" for /d %%P in ("%APPDATA%\\shield-dev-wt\\*") do call :scanEndpointDir "%%~fP\\agent-hooks"',
      'if "%OSHIELD_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\shield\\agent-hooks" for /r "%APPDATA%\\shield\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':scanEndpointDir',
      'if not "%OSHIELD_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'if exist "%~1" for /r "%~1" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%OSHIELD_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set OSHIELD_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%OSHIELD_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__shield_read_ancestor_var() {',
    '  __shield_name="$1"',
    '  __shield_pid="${PPID:-}"',
    '  while [ -n "$__shield_pid" ] && [ "$__shield_pid" != "0" ] && [ "$__shield_pid" != "1" ]; do',
    '    __shield_value=""',
    '    if [ -r "/proc/$__shield_pid/environ" ]; then',
    '      __shield_value=$(tr "\\000" "\\n" < "/proc/$__shield_pid/environ" 2>/dev/null | sed -n "s/^${__shield_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__shield_value" ]; then',
    '      __shield_value=$(ps eww -p "$__shield_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__shield_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__shield_value" ]; then',
    '      printf "%s\\n" "$__shield_value"',
    '      return 0',
    '    fi',
    '    __shield_pid=$(ps -o ppid= -p "$__shield_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__shield_fill_from_ancestor() {',
    '  __shield_name="$1"',
    '  case "$__shield_name" in',
    '    OSHIELD_AGENT_HOOK_ENDPOINT) [ -z "${OSHIELD_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    OSHIELD_AGENT_HOOK_PORT) [ -z "${OSHIELD_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    OSHIELD_AGENT_HOOK_TOKEN) [ -z "${OSHIELD_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    OSHIELD_AGENT_HOOK_ENV) [ -z "${OSHIELD_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    OSHIELD_AGENT_HOOK_VERSION) [ -z "${OSHIELD_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    OSHIELD_PANE_KEY) [ -z "${OSHIELD_PANE_KEY:-}" ] || return 0 ;;',
    '    OSHIELD_TAB_ID) [ -z "${OSHIELD_TAB_ID:-}" ] || return 0 ;;',
    '    OSHIELD_WORKTREE_ID) [ -z "${OSHIELD_WORKTREE_ID:-}" ] || return 0 ;;',
    '    OSHIELD_AGENT_LAUNCH_TOKEN) [ -z "${OSHIELD_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __shield_value=$(__shield_read_ancestor_var "$__shield_name") || return 0',
    '  [ -n "$__shield_value" ] && export "$__shield_name=$__shield_value"',
    '}',
    '__shield_endpoint_value() {',
    '  __shield_endpoint_name="$1"',
    '  __shield_endpoint_path="$2"',
    '  sed -n "s/^${__shield_endpoint_name}=//p" "$__shield_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__shield_fill_from_endpoint_file() {',
    '  __shield_endpoint_path="$1"',
    '  [ -r "$__shield_endpoint_path" ] || return 0',
    '  __shield_endpoint_port=$(__shield_endpoint_value OSHIELD_AGENT_HOOK_PORT "$__shield_endpoint_path")',
    '  if [ -n "${OSHIELD_AGENT_HOOK_PORT:-}" ] && [ -n "$__shield_endpoint_port" ] && [ "$__shield_endpoint_port" != "$OSHIELD_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __shield_endpoint_name in OSHIELD_AGENT_HOOK_PORT OSHIELD_AGENT_HOOK_TOKEN OSHIELD_AGENT_HOOK_ENV OSHIELD_AGENT_HOOK_VERSION; do',
    '    eval "__shield_current=\\${$__shield_endpoint_name:-}"',
    '    [ -z "$__shield_current" ] || continue',
    '    __shield_endpoint_value=$(__shield_endpoint_value "$__shield_endpoint_name" "$__shield_endpoint_path")',
    '    [ -n "$__shield_endpoint_value" ] && export "$__shield_endpoint_name=$__shield_endpoint_value"',
    '  done',
    '}',
    '# Recover pane/hook metadata from the parent TUI after Command Code sanitizes hook env.',
    'for __shield_name in OSHIELD_AGENT_HOOK_ENDPOINT OSHIELD_AGENT_HOOK_PORT OSHIELD_AGENT_HOOK_TOKEN OSHIELD_AGENT_HOOK_ENV OSHIELD_AGENT_HOOK_VERSION OSHIELD_PANE_KEY OSHIELD_TAB_ID OSHIELD_WORKTREE_ID OSHIELD_AGENT_LAUNCH_TOKEN; do',
    '  __shield_fill_from_ancestor "$__shield_name"',
    'done',
    'if [ -n "$OSHIELD_AGENT_HOOK_ENDPOINT" ] && [ -r "$OSHIELD_AGENT_HOOK_ENDPOINT" ]; then',
    '  __shield_fill_from_endpoint_file "$OSHIELD_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Recover stripped token metadata by matching the preserved loopback port.',
    'if [ -z "$OSHIELD_AGENT_HOOK_TOKEN" ] && [ -n "$OSHIELD_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/shield-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/shield-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/shield-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/shield-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/shield-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/shield-dev-wt"/*/agent-hooks/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/shield/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/shield/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^OSHIELD_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$OSHIELD_AGENT_HOOK_PORT" ]; then',
    '      __shield_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$OSHIELD_AGENT_HOOK_PORT" ] || [ -z "$OSHIELD_AGENT_HOOK_TOKEN" ] || [ -z "$OSHIELD_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Bound stalled posts and pipe large payloads through stdin to avoid EDR command-line false positives.
    `printf '%s' "$payload" | ${posixCurlCommand()} -sS -X POST "http://127.0.0.1:\${OSHIELD_AGENT_HOOK_PORT}/hook/command-code" \\`,
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Shield-Agent-Hook-Token: ${OSHIELD_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${OSHIELD_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${OSHIELD_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${OSHIELD_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${OSHIELD_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${OSHIELD_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${OSHIELD_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
